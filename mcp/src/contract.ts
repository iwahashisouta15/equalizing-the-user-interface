export function generateUiContract(): string {
  return `/** Generated by Equalizing the User Interface MCP. Adapt only to the existing UI contract. */
export type ChatRole = 'system' | 'user' | 'assistant';

export interface ChatMessage {
  role: ChatRole;
  content: string;
}

export type UiStatus = 'idle' | 'loading' | 'error';

export interface Provider {
  id: string;
  send(messages: ChatMessage[], options?: { signal?: AbortSignal }): AsyncIterable<string>;
}

export interface UiActions {
  send(messages: ChatMessage[]): Promise<void>;
  cancel(): void;
}
`;
}
